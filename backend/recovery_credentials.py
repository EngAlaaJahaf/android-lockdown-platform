"""RecoveryVault — per-device, system-generated recovery credentials (§7/§8/§16).

One random 256-bit credential per device, generated by the system:
  - never shared between devices (Device A -> Recovery A only);
  - never shown to the end user; reports expose only
    `Recovery: Configured` and `Recovery ID: XXXX-XXXX`;
  - never stored in plaintext: AES-256-GCM. The per-device encryption key is
    HKDF(root_key, device_id). The root key is wrapped with Windows DPAPI
    (CryptProtectData) by default; tests / non-Windows callers MUST inject an
    explicit root_key (test-only protection strategy, never the default).

This is NOT a backdoor: it only authorizes this platform's own management
actions. It never claims to bypass FRP / secure boot / bootloader / Knox /
OEM lock / Google protections — the engines only use legitimate management
mechanisms (Device Owner / DPC / enrollment).
"""
from __future__ import annotations

import os
import secrets
import sys
import time
from typing import Optional

from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from cryptography.hazmat.primitives.hashes import SHA256
from cryptography.hazmat.primitives.kdf.hkdf import HKDF

from .db import connect
from .config import DBPATH

AAD_PREFIX = b"alp-recovery-vault|"
ROOT_ENTROPY = b"alp-recovery-root-key"


class RecoveryVaultUnavailable(Exception):
    """The encrypted vault cannot be opened (e.g. Windows DPAPI unavailable)."""


def _hkdf(ikm: bytes, device_id: str) -> bytes:
    info = AAD_PREFIX + device_id.encode("utf-8")
    return HKDF(algorithm=SHA256(), length=32, salt=None, info=info).derive(ikm)


def _gcm_encrypt(key: bytes, nonce: bytes, payload: bytes, aad: bytes) -> bytes:
    return AESGCM(key).encrypt(nonce, payload, aad)


def _gcm_decrypt(key: bytes, nonce: bytes, ct: bytes, aad: bytes) -> bytes:
    return AESGCM(key).decrypt(nonce, ct, aad)


# ---------------------------------------------------------------------------
# Windows DPAPI helpers (stdlib ctypes) — protects the root key at rest.
# ---------------------------------------------------------------------------
def _dpapi_available() -> bool:
    return sys.platform == "win32"


def _dpapi_protect(data: bytes, entropy: bytes) -> bytes:
    import ctypes
    from ctypes import wintypes

    class DATA_BLOB(ctypes.Structure):
        _fields_ = [("cbData", wintypes.DWORD),
                    ("pbData", ctypes.POINTER(ctypes.c_char))]

    def blob(b: bytes):
        buf = ctypes.create_string_buffer(b)
        return DATA_BLOB(len(b), ctypes.cast(buf, ctypes.POINTER(ctypes.c_char))), buf

    ent, ent_keep = blob(entropy)
    inp, inp_keep = blob(data)
    out = DATA_BLOB()
    ok = ctypes.windll.crypt32.CryptProtectData(
        ctypes.byref(inp), None, ctypes.byref(ent), None, None, 0,
        ctypes.byref(out))
    if not ok:
        raise OSError("CryptProtectData failed")
    try:
        return bytes(ctypes.string_at(out.pbData, out.cbData))
    finally:
        ctypes.windll.kernel32.LocalFree(out.pbData)


def _dpapi_unprotect(blob: bytes, entropy: bytes) -> bytes:
    import ctypes
    from ctypes import wintypes

    class DATA_BLOB(ctypes.Structure):
        _fields_ = [("cbData", wintypes.DWORD),
                    ("pbData", ctypes.POINTER(ctypes.c_char))]

    def bblob(b: bytes):
        buf = ctypes.create_string_buffer(b)
        return DATA_BLOB(len(b), ctypes.cast(buf, ctypes.POINTER(ctypes.c_char))), buf

    ent, ent_keep = bblob(entropy)
    inp, inp_keep = bblob(blob)
    out = DATA_BLOB()
    ok = ctypes.windll.crypt32.CryptUnprotectData(
        ctypes.byref(inp), None, ctypes.byref(ent), None, None, 0,
        ctypes.byref(out))
    if not ok:
        raise OSError("CryptUnprotectData failed")
    try:
        return bytes(ctypes.string_at(out.pbData, out.cbData))
    finally:
        ctypes.windll.kernel32.LocalFree(out.pbData)


# ---------------------------------------------------------------------------
# RecoveryVault
# ---------------------------------------------------------------------------
class RecoveryVault:
    """Encrypted store of per-device recovery credentials.

    root_key: injected by tests/non-Windows callers (explicit opt-in).
    On Windows with no injected key the root key lives in a DPAPI-protected
    file `vault.key` next to the database (never plaintext).
    """

    def __init__(self, db_path: Optional[str] = None,
                 root_key: Optional[bytes] = None,
                 root_key_file: Optional[str] = None):
        self.db_path = db_path
        self.root_key = self._load_root_key(root_key, root_key_file)

    # -- root key ---------------------------------------------------------
    def _load_root_key(self, injected: Optional[bytes],
                       key_file: Optional[str]) -> bytes:
        if injected is not None:
            if len(injected) < 16:
                raise ValueError("root_key too short — use >= 16 bytes")
            return bytes(injected)
        if not _dpapi_available():
            raise RecoveryVaultUnavailable(
                "DPAPI is unavailable on this platform — RecoveryVault requires "
                "an explicit root_key (test configuration) or Windows.")
        base = os.path.dirname(os.path.abspath(self.db_path or DBPATH))
        kf = key_file or os.path.join(base, "vault.key")
        try:
            with open(kf, "rb") as fh:
                wrapped = fh.read()
        except FileNotFoundError:
            key = secrets.token_bytes(32)
            wrapped = _dpapi_protect(key, ROOT_ENTROPY)
            os.makedirs(os.path.dirname(kf), exist_ok=True)
            try:
                with open(kf, "wb") as fh:
                    fh.write(wrapped)
            finally:
                pass
            return key
        except OSError:
            raise RecoveryVaultUnavailable(f"cannot read vault key at {kf}")
        try:
            return _dpapi_unprotect(wrapped, ROOT_ENTROPY)
        except Exception as ex:  # noqa: BLE001
            raise RecoveryVaultUnavailable(
                f"cannot unprotect vault root key (wrong Windows user / file "
                f"copied to another machine?): {type(ex).__name__}")

    # -- row helpers ------------------------------------------------------
    def _row(self, device_id: str) -> Optional[dict]:
        with connect(self.db_path) as c:
            r = c.execute(
                "SELECT device_id, recovery_id, credential_ciphertext, nonce, "
                "revoked FROM recovery_credentials WHERE device_id=?",
                (device_id,)).fetchone()
        return dict(r) if r else None

    def _decrypt(self, row: dict) -> bytes:
        key = _hkdf(self.root_key, row["device_id"])
        return _gcm_decrypt(key, bytes(row["nonce"]),
                            bytes(row["credential_ciphertext"]),
                            AAD_PREFIX + row["device_id"].encode("utf-8"))

    def _new_id(self) -> str:
        while True:
            rid = f"{secrets.token_hex(2).upper()}-{secrets.token_hex(2).upper()}"
            with connect(self.db_path) as c:
                if not c.execute("SELECT 1 FROM recovery_credentials "
                                 "WHERE recovery_id=?", (rid,)).fetchone():
                    return rid

    def _store(self, device_id: str, credential: bytes, rotate: bool) -> dict:
        key = _hkdf(self.root_key, device_id)
        nonce = secrets.token_bytes(12)
        ct = _gcm_encrypt(key, nonce, credential,
                          AAD_PREFIX + device_id.encode("utf-8"))
        rid = self._new_id()
        now = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
        with connect(self.db_path) as c:
            c.execute(
                """INSERT INTO recovery_credentials
                       (device_id, recovery_id, credential_ciphertext,
                        nonce, rotated_at)
                   VALUES (?,?,?,?,?)
                   ON CONFLICT(device_id) DO UPDATE SET
                       recovery_id=excluded.recovery_id,
                       credential_ciphertext=excluded.credential_ciphertext,
                       nonce=excluded.nonce, revoked=0,
                       rotated_at=excluded.rotated_at""",
                (device_id, rid, ct, nonce, now if rotate else None))
        return {"ok": True, "device_id": device_id, "recovery_id": rid,
                "rotated": rotate, "recovery": "Configured"}

    # -- public API -------------------------------------------------------
    def generate_for(self, device_id: str) -> dict:
        credential = secrets.token_bytes(32)
        return self._store(device_id, credential, rotate=False)

    def ensure_for(self, device_id: str) -> dict:
        """Idempotent: generate a credential on first registration/use."""
        st = self.status(device_id)
        if st["recovery"] in ("Configured", "Mismatch"):
            return st
        return self.generate_for(device_id)

    def rotate_for(self, device_id: str) -> dict:
        credential = secrets.token_bytes(32)
        return self._store(device_id, credential, rotate=True)

    def revoke_for(self, device_id: str) -> dict:
        with connect(self.db_path) as c:
            c.execute(
                """UPDATE recovery_credentials SET revoked=1,
                       rotated_at=datetime('now')
                   WHERE device_id=? AND revoked=0""", (device_id,))
        return self.status(device_id)

    def verify_for(self, device_id: str) -> dict:
        """Possession-factor gate for a sensitive operation on `device_id`.
        Returns {'ok': bool, 'reason': str}."""
        row = self._row(device_id)
        if row is None:
            return {"ok": False,
                    "reason": f"no recovery credential configured for {device_id}"
                              " — sensitive operation blocked"}
        if row["revoked"]:
            return {"ok": False, "reason": "recovery credential revoked"}
        try:
            raw = self._decrypt(row)
        except Exception as ex:  # noqa: BLE001
            return {"ok": False,
                    "reason": f"recovery credential mismatch (integrity/entropy "
                              f"failure): {type(ex).__name__}"}
        if len(raw) != 32:
            return {"ok": False, "reason": "invalid credential length"}
        return {"ok": True, "reason": ""}

    def status(self, device_id: str) -> dict:
        """Display-only status; NEVER includes the secret."""
        row = self._row(device_id)
        if row is None:
            return {"recovery": "Not Configured", "recovery_id": ""}
        if row["revoked"]:
            return {"recovery": "Revoked", "recovery_id": row["recovery_id"]}
        try:
            self._decrypt(row)
            label = "Configured"
        except Exception:  # noqa: BLE001
            label = "Mismatch"
        return {"recovery": label, "recovery_id": row["recovery_id"]}

    def summary(self) -> list:
        """Per-device display-only status (never the secret) for fleet views."""
        with connect(self.db_path) as c:
            rows = c.execute(
                "SELECT device_id FROM devices ORDER BY id").fetchall()
        return [{"device_id": r["device_id"],
                 **self.status(r["device_id"])} for r in rows]

    def available(self) -> bool:
        return self.root_key is not None